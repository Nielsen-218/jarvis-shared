import assert from 'node:assert/strict';
import * as T from '../../app/vendor/three/three.module.min.js';
import { attachNativeAnimations } from '../../app/companion/native-animation.js';
const model=new T.Group(), group=new T.Group(), head=new T.Bone(), hips=new T.Bone();
head.name='Head'; hips.name='Hips'; hips.add(head);model.add(hips);group.add(model);
head.rotation.x=.4;
const q0=head.quaternion.clone(), q1=new T.Quaternion().setFromEuler(new T.Euler(.8,0,0));
const clip=(name,q)=>new T.AnimationClip(name,1,[new T.QuaternionKeyframeTrack('Head.quaternion',[0,1],[...q.toArray(),...q.toArray()])]);
const adapter={group,bones:{root:hips,head},capabilities:{},dispose(){}};
attachNativeAnimations(T,adapter,model,[clip('Agree_Gesture',q0),clip('Hip_Hop_Dance_3',q1)]);
assert.equal(adapter.bones.root,group);
assert.notEqual(adapter.bones.head,head);
adapter.bones.head.rotation.y=.15;
const expected=q0.clone().multiply(adapter.bones.head.quaternion);
adapter.sync();adapter.sync();
assert.ok(head.quaternion.angleTo(expected)<.001,'repeated sync preserves the animated rest pose without accumulation');
adapter.updateAnimation('dance',0);adapter.sync();
assert.ok(head.quaternion.angleTo(q1.clone().multiply(adapter.bones.head.quaternion))<.001,'dance uses native clip');
adapter.updateAnimation('dance',0,null,true);adapter.sync();
assert.ok(head.quaternion.angleTo(expected)<.001,'reduced motion suppresses native dance');
adapter.dispose();
console.log('native animation: 6 checks passed');
