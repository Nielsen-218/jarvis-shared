"""Render the built Project Captain America plan (core/pca_program.build, the 5-day layout) to Markdown.

    python -m scripts.pca_render [--days 5|6] [--out docs/pca/PROGRAM-12-WEEKS.md]

The document is generated from the same data the trainer runs, so it can never drift from the program. Nothing here
is hand-written per week; edit core/pca_program.py and render again."""
import argparse
from datetime import date
from pathlib import Path

from core import pca_program as program

ROOT = Path(__file__).resolve().parent.parent


def _cell(text) -> str:
    return str(text if text not in (None, "") else "-").replace("|", "/").replace("\n", " ")


def _warm(day: dict) -> str:
    parts = []
    for phase in day["warmup"] or []:
        parts.append(f"{phase['phase']}: " + "; ".join(f"{i['exercise'].replace('_', ' ')} {i['dose']}" for i in phase["items"]))
    return " / ".join(parts) or "none (optional recovery day)"


def _cool(day: dict) -> str:
    return "; ".join(f"{i['exercise'].replace('_', ' ')} {i['dose']}" for i in day["cooldown"] or []) or "-"


def _intensity(it: dict) -> str:
    if it["kind"] == "lift":
        return f"{it['rir']} RIR" + (f", tempo {it['tempo']}" if it.get("tempo") else "")
    if it.get("pct_of"):
        return f"{round(it['pct'] * 100)}% of tested {it['pct_of'].upper()}"
    return it["target"]


def render(days_per_week: int = 5) -> str:
    plan = program.build({"days_per_week": days_per_week}, date(2026, 1, 5))
    problems = program.verify(plan)
    lines = [f"# {plan['name']} ({plan['days_per_week']}-day layout)", "",
             "Generated by `python -m scripts.pca_render` from `core/pca_program.py`. Do not edit by hand.", "",
             f"> {plan['notes'][-1]}", "", plan["why"], "",
             f"Structural review (`pca_program.verify`): {'passes, no problems found' if not problems else '; '.join(problems)}.", "",
             "Loads are set by reps in reserve (RIR) and then follow what is logged. Run paces exist only after the two-mile "
             "time trial inside the program; until then runs go by RPE and the talk test. Shares of a tested max (HRP push-ups, "
             "PLK plank) become numbers only after the in-program test.", "", "## Phases", ""]
    for b in plan["blocks"]:
        lines.append(f"- **{b['name']}** (weeks {b['weeks'][0]}-{b['weeks'][-1]}): {b['goal']}")
    lines += ["", "## Run intensity zones", "", "| Zone | Name | RPE | Talk test | Factor on tested two-mile pace |", "|---|---|---|---|---|"]
    for z, v in program.ZONES.items():
        lines.append(f"| {z} | {v['name']} | {v['rpe']} | {v['talk']} | {v['factor'][0]}-{v['factor'][1]} |")
    lines += ["", "## Weekly summary", "", "| Week | Mode | Lifting sets | Run min | Hard run min | Sprint m | Minutes Mon-Sat |",
              "|---|---|---|---|---|---|---|"]
    for row in program.summary(plan):
        lines.append(f"| {row['week']} | {row['mode']} | {row['lift_sets']} | {row['run_min']} | {row['hard_run_min']} | {row['sprint_m']} | "
                     + ", ".join(f"{d} {m}" for d, m in row["minutes"].items()) + " |")
    for wk in plan["weeks"]:
        lines += ["", f"## Week {wk['week']}: {wk['focus']}", "", f"{wk['block_name']}; mode: {wk['mode']}.", ""]
        for d in wk["days"]:
            lines += [f"### {d['day']}: {d['title']}", "",
                      f"*{d['intensity']} intensity{', optional' if d['optional'] else ''}, about {d['minutes']} min.* {d['why']}", "",
                      f"Stimulus: {d['stimulus']}", "", f"**Warm-up:** {_warm(d)}", ""]
            lines += ["| Exercise | Sets | Reps | Intensity / target | Rest | Purpose | Equipment | Alternatives | Progression |",
                      "|---|---|---|---|---|---|---|---|---|"]
            for it in d["items"]:
                lines.append("| " + " | ".join(_cell(x) for x in (it["exercise"], it["sets"], it["reps"], _intensity(it), it.get("rest"),
                                                                       it["purpose"], it["equipment"], ", ".join(it["alternatives"]),
                                                                       it["progression"])) + " |")
            notes = [f"{it['exercise']}: {it['notes']}" for it in d["items"] if it.get("notes")]
            if d["trimmed"]:
                notes.append("Trimmed to fit the session length: " + ", ".join(d["trimmed"]))
            if d["notes"]:
                notes.append(d["notes"])
            lines += [""] + [f"- {n}" for n in notes] + ([""] if notes else []) + [f"**Cool-down:** {_cool(d)}", ""]
    lines += ["## After week 12", "", program.LONG_TERM["week_13"], ""]
    for b in program.LONG_TERM["blocks"]:
        lines.append(f"- **{b['name']}** ({b['weeks']} weeks): {b['goal']}")
    lines += ["", "Next-block emphasis by the weakest week-12 event:", ""]
    lines += [f"- {ev.upper()}: {text}" for ev, text in program.LONG_TERM["emphasis"].items()]
    lines += ["", "Plateaus:", ""] + [f"- {p}" for p in program.LONG_TERM["plateau"]] + [""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--days", type=int, default=5, choices=(5, 6))
    ap.add_argument("--out", default=str(ROOT / "docs" / "pca" / "PROGRAM-12-WEEKS.md"))
    a = ap.parse_args()
    Path(a.out).write_text(render(a.days), encoding="utf-8")
    print(f"wrote {a.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
